// TestMerkleizeEntriesEdges covers the empty and single-entry tables: an
// empty table has no entries to hash and no root (the zero hash), and a
// single-entry table mixes the count into the leaf itself.
func TestMerkleizeEntriesEdges(t *testing.T) {
	if root := merkleizeEntries(nil); root != (common.Hash{}) {
		t.Errorf("empty table root = %x, want the zero hash", root)
	}
	if root := naiveTableRoot(nil); root != (common.Hash{}) {
		t.Errorf("naive oracle empty table root = %x, want the zero hash", root)
	}
}

// syntheticEntries regenerates the golden vector scheme with canonical
// addresses (IndexEntry carries the low 20 bytes of the value, equivalent to
// a zeroed top), so the vector ordering and the encoding ordering coincide.
func syntheticEntries(n int) []IndexEntry {
	entries := make([]IndexEntry, n)
	for i := 0; i < n; i++ {
		value := sha256.Sum256(binary.BigEndian.AppendUint64(nil, uint64(i)))
		typ := EntryType(i % 7)
		content := value[:]
		if typ == EntryTypeLogAddress {
			content = value[12:]
		}
		entries[i] = EncodeEntry(typ, content, 1000000+3*uint64(i), uint32(i%5), uint32(i%3))
	}
	sort.Slice(entries, func(i, j int) bool {
		return CompareEntries(entries[i], entries[j]) < 0
	})
	return entries
}

// TestMerkleizeEntriesDifferential cross-checks the hand-rolled tree against
// fastssz's MerkleizeWithMixin over the same leaf sequence, and against the
// naive oracle, for sizes spanning even/odd, powers of two and padded shapes.
func TestMerkleizeEntriesDifferential(t *testing.T) {
	for _, n := range []int{1, 2, 3, 4, 5, 6, 7, 8, 9, 15, 16, 17, 31, 32, 33, 63, 64, 100, 255, 256, 257, 1000} {
		entries := syntheticEntries(n)
		hh := ssz.NewHasher()
		for _, entry := range entries {
			leaf := sha256.Sum256(entry)
			hh.Append(leaf[:])
		}
		hh.MerkleizeWithMixin(0, uint64(n), uint64(n))
		root, err := hh.HashRoot()
		if err != nil {
			t.Fatalf("n=%d: fastssz HashRoot error: %v", n, err)
		}
		if got := merkleizeEntries(entries); (common.Hash)(root) != got {
			t.Errorf("n=%d: merkleizeEntries root %x, fastssz root %x", n, got, root)
		}
		if got := naiveTableRoot(entries); got != merkleizeEntries(entries) {
			t.Errorf("n=%d: naive oracle root %x differs from merkleizeEntries", n, got)
		}
	}
}
