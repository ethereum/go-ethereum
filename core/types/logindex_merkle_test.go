// naiveTableRoot is an independent oracle for merkleizeEntries: it pads the
// leaf list with zero leaves to the full 2^ceil(log2(n)) width and folds
// naively, instead of growing the layer with zero-subtree ladder entries. The
// two constructions are equivalent because sha256(z || z) makes an explicit
// zero-leaf subtree hash to the ladder value of the same height.
func naiveTableRoot(entries []IndexEntry) common.Hash {
	n := len(entries)
	if n == 0 {
		return common.Hash{}
	}
	width := 1 << bits.Len(uint(n-1)) // 2^ceil(log2(n)); 1 for n == 1
	layer := make([][32]byte, width)
	hasher := sha256.New()
	for i, entry := range entries {
		hasher.Reset()
		hasher.Write(entry)
		hasher.Sum(layer[i][:0])
	}
	for count := width; count > 1; count /= 2 {
		for i := 0; i < count/2; i++ {
			hasher.Reset()
			hasher.Write(layer[2*i][:])
			hasher.Write(layer[2*i+1][:])
			hasher.Sum(layer[i][:0])
		}
	}
	var countEnc [32]byte
	binary.LittleEndian.PutUint64(countEnc[:8], uint64(n))
	hasher.Reset()
	hasher.Write(layer[0][:])
	hasher.Write(countEnc[:])
	var root common.Hash
	hasher.Sum(root[:0])
	return root
}

