package pathdb

import (
	"github.com/ethereum/go-ethereum/common"
	"github.com/ethereum/go-ethereum/core/rawdb"
	"github.com/ethereum/go-ethereum/core/types"
	"github.com/ethereum/go-ethereum/crypto"
	"github.com/ethereum/go-ethereum/trie/pbt"
)

// stateTrie contains the trie-specific behavior of the database.
type stateTrie interface {
	// config returns the configuration associated with that particular
	// trie implementation.
	config() trieConfig

	// hashRoot hashes a serialized root node, or returns the empty trie root
	// when blob is empty.
	hashRoot(blob []byte) (common.Hash, error)
}

// trieConfig describes storage conventions and supported operations of a trie.
type trieConfig struct {
	name               string // Trie implementation name
	namespace          []byte // Database namespace, shared by the trie and its flat state
	journalName        string // Journal filename, preserving existing storage conventions
	verifyNodeHash     bool   // Whether node hashes can be checked by the generic node reader
	generateState      bool   // Whether flat state can be generated by walking the trie
	stateHistoryName   string // Name of the flat state history freezer
	nodeHistoryName    string // Name of the trie node history freezer
	nodeHistory        bool   // Whether trie node history encoding and indexing are supported
	recoverState       bool   // Whether state history can be replayed to recover trie nodes
	completeEmptyState bool   // Whether an empty trie starts with complete flat state
}

// mptTrie is the Merkle Patricia trie implementation.
type mptTrie struct{}

func (mptTrie) config() trieConfig {
	return trieConfig{
		name:             "mpt",
		stateHistoryName: rawdb.MerkleStateFreezerName,
		nodeHistoryName:  rawdb.MerkleTrienodeFreezerName,
		journalName:      "merkle.journal",
		verifyNodeHash:   true,
		generateState:    true,
		nodeHistory:      true,
		recoverState:     true,
	}
}

func (mptTrie) hashRoot(blob []byte) (common.Hash, error) {
	if len(blob) == 0 {
		return types.EmptyRootHash, nil
	}
	return crypto.Keccak256Hash(blob), nil
}

// pbtTrie is the EIP-8297 partitioned binary trie implementation.
type pbtTrie struct{}

func (pbtTrie) config() trieConfig {
	return trieConfig{
		name:               "pbt",
		namespace:          rawdb.PBTPrefix,
		stateHistoryName:   rawdb.PBTStateFreezerName,
		nodeHistoryName:    rawdb.PBTTrienodeFreezerName,
		journalName:        "pbt.journal",
		completeEmptyState: true,
	}
}

func (pbtTrie) hashRoot(blob []byte) (common.Hash, error) {
	return pbt.DeserializeAndHash(blob)
}
