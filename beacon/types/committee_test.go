package types

import (
	"testing"

	"github.com/ethereum/go-ethereum/common"
)

// TestSerializedSyncCommitteeRoot pins SerializedSyncCommittee.Root to known
// roots. The inputs are generated by a byte fill so they need not be embedded.
func TestSerializedSyncCommitteeRoot(t *testing.T) {
	tests := []struct {
		name string
		fill func(i int) byte
		want common.Hash
	}{
		{
			name: "zero",
			fill: func(i int) byte { return 0 },
			want: common.HexToHash("0x173669ae8794c057def63b20372114a628abb029354a2ef50d7a1aaa9a3dab4a"),
		},
		{
			name: "ramp",
			fill: func(i int) byte { return byte(i) },
			want: common.HexToHash("0x5995a285cb1439bc2a8e89cd5d399cfaa5f845926a230671021dd0418cc3350b"),
		},
		{
			name: "ramp251",
			fill: func(i int) byte { return byte(i % 251) },
			want: common.HexToHash("0xd6b0cecb0ea03992426a40b0d9a711cd2aa8ae508215b99285c8846da55d2485"),
		},
	}
	for _, test := range tests {
		var s SerializedSyncCommittee
		for i := range s {
			s[i] = test.fill(i)
		}
		if got := s.Root(); got != test.want {
			t.Errorf("%s: root mismatch: got %x, want %x", test.name, got, test.want)
		}
	}
}
